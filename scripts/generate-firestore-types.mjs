// The status enum gets a shorter Go type name than the other enums
// (FirestoreJobStatusState, not FirestoreJobStatusStatus) because it reads
// better at every call site. Kept as a special case rather than a rename so
// existing code does not churn.
function enumTypeName(target, propName) {
  return propName === 'status'
    ? `${target.typeName}State`
    : `${target.typeName}${goName(target, propName)}`;
}

function goName(target, name) {
  if (target.goNameOverrides[name]) return target.goNameOverrides[name];
  return name[0].toUpperCase() + name.slice(1);
}

function typeFor(prop) {
  if (prop['x-firestore-timestamp']) {
    // Firestore Timestamp values arrive on the client as a native Timestamp
    // object from the firebase SDK; we leave the type open here because the
    // app rarely reads expiresAt directly (its purpose is TTL on the server).
    return 'unknown';
  }
  if (Array.isArray(prop.enum)) {
    return prop.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  switch (prop.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'string':
      return 'string';
    case 'array':
      if (!prop.items) throw new Error(`array property is missing items: ${JSON.stringify(prop)}`);
      return `${typeFor(prop.items)}[]`;
    default:
      throw new Error(`Unsupported schema type: ${JSON.stringify(prop)}`);
  }
}

function goType(target, name, prop, optional) {
  if (prop['x-firestore-timestamp']) {
    // Firestore SDK round-trips time.Time <-> Firestore Timestamp, which is
    // what the TTL policy field selector needs.
    return optional ? '*time.Time' : 'time.Time';
  }
  if (Array.isArray(prop.enum)) {
    const typ = enumTypeName(target, name);
    return optional ? `*${typ}` : typ;
  }
  if (prop.type === 'array') {
    if (!prop.items) throw new Error(`array property is missing items: ${JSON.stringify(prop)}`);
    // Slices are already nullable in Go, so the optional pointer wrap is
    // skipped; a missing field is the empty slice.
    const elem = prop.items.type === 'integer' || prop.items.type === 'number' ? 'int' : 'string';
    return `[]${elem}`;
  }
  let typ = 'string';
  if (prop.type === 'integer' || prop.type === 'number') typ = 'int';
  else if (prop.type === 'boolean') typ = 'bool';
  return optional ? `*${typ}` : typ;
}

function buildTS(target, schema, required) {
  const lines = [
    '// @generated by scripts/generate-firestore-types.mjs',
    `// Source: ${target.schema}`,
    '',
    `export type ${target.typeName} = {`,
  ];

  for (const [name, prop] of Object.entries(schema.properties ?? {})) {
    const optional = required.has(name) ? '' : '?';
    lines.push(`  ${name}${optional}: ${typeFor(prop)};`);
  }

  lines.push('};', '');
  return lines.join('\n');
}

function buildGo(target, schema, required) {
  const properties = Object.entries(schema.properties ?? {});
  const usesTime = properties.some(([, p]) => p['x-firestore-timestamp']);

  const lines = [
    '// Code generated by scripts/generate-firestore-types.mjs; DO NOT EDIT.',
    `// Source: ${target.schema}`,
    '',
    `package ${target.goPackage}`,
    '',
  ];

  if (usesTime) {
    lines.push('import "time"', '');
  }

  const embeddedSchema = JSON.stringify(schema, null, 2).replaceAll('`', '` + "`" + `');
  lines.push(`const ${target.typeName}JSONSchema = \`${embeddedSchema}\``, '');

  // status first so its type is declared before the remaining enums, matching
  // the order the file has always had.
  if (schema.properties?.status?.enum) {
    const typ = enumTypeName(target, 'status');
    lines.push(`type ${typ} string`, '', 'const (');
    for (const value of schema.properties.status.enum) {
      const suffix = value[0].toUpperCase() + value.slice(1);
      lines.push(`\t${typ}${suffix} ${typ} = ${JSON.stringify(value)}`);
    }
    lines.push(')', '');
  }

  for (const [name, prop] of properties) {
    if (!Array.isArray(prop.enum) || name === 'status') continue;
    const typ = enumTypeName(target, name);
    lines.push(`type ${typ} string`, '', 'const (');
    for (const value of prop.enum) {
      const suffix = value
        .split(/[._-]/)
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('');
      lines.push(`\t${typ}${suffix} ${typ} = ${JSON.stringify(value)}`);
    }
    lines.push(')', '');
  }

  lines.push('const (');
  for (const [name] of properties) {
    lines.push(`\t${target.typeName}Field${goName(target, name)} = ${JSON.stringify(name)}`);
  }
  lines.push(')', '');

  lines.push(`type ${target.typeName} struct {`);
  for (const [name, prop] of properties) {
    const optional = !required.has(name);
    const omitempty = optional ? ',omitempty' : '';
    lines.push(
      `\t${goName(target, name)} ${goType(target, name, prop, optional)} \`firestore:"${name}${omitempty}" json:"${name}${omitempty}"\``,
    );
  }
  lines.push('}', '');

  return lines.join('\n');
}

for (const target of targets) {
  const schema = JSON.parse(readFileSync(resolve(root, target.schema), 'utf8'));
  const required = new Set(schema.required ?? []);

  writeFileSync(resolve(root, target.tsOut), buildTS(target, schema, required));

  const goOutPath = resolve(root, target.goOut);
  writeFileSync(goOutPath, buildGo(target, schema, required));
  // The emitted Go is not column-aligned. gofmt runs here so the committed
  // files are reproducible: without it, regenerating produces a diff against
  // what is checked in and the check below can never pass.
  execFileSync('gofmt', ['-w', goOutPath]);

  console.log(`generated ${target.tsOut}`);
  console.log(`generated ${target.goOut}`);
}

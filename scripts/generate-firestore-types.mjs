import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const schemaPath = resolve(root, 'contracts/firestore/job-status.schema.json');
const tsOutPath = resolve(root, 'apps/web/src/features/jobs/firestoreJobStatus.generated.ts');
const goOutPath = resolve(root, 'internal/platform/job/status/firestore_job_status.generated.go');

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
const required = new Set(schema.required ?? []);

function typeFor(prop) {
  if (Array.isArray(prop.enum)) {
    return prop.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  switch (prop.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'string':
      return 'string';
    default:
      throw new Error(`Unsupported schema type: ${JSON.stringify(prop)}`);
  }
}

const tsLines = [
  '// @generated by scripts/generate-firestore-types.mjs',
  '// Source: contracts/firestore/job-status.schema.json',
  '',
  'export type FirestoreJobStatus = {',
];

for (const [name, prop] of Object.entries(schema.properties ?? {})) {
  const optional = required.has(name) ? '' : '?';
  tsLines.push(`  ${name}${optional}: ${typeFor(prop)};`);
}

tsLines.push('};', '');

writeFileSync(tsOutPath, tsLines.join('\n'));

const goNameOverrides = {
  jobId: 'JobID',
  jobType: 'JobType',
  documentId: 'DocumentID',
  workspaceId: 'WorkspaceID',
  treeId: 'TreeID',
  currentStage: 'CurrentStage',
  errorMessage: 'ErrorMessage',
  suggestedWorkspaceName: 'SuggestedWorkspaceName',
  suggestedWorkspaceNameSource: 'SuggestedWorkspaceNameSource',
  createdAt: 'CreatedAt',
  startedAt: 'StartedAt',
  updatedAt: 'UpdatedAt',
  completedAt: 'CompletedAt',
};

function goName(name) {
  if (goNameOverrides[name]) return goNameOverrides[name];
  return name[0].toUpperCase() + name.slice(1);
}

function goType(name, prop, optional) {
  if (Array.isArray(prop.enum)) {
    const typ = name === 'status'
      ? 'FirestoreJobStatusState'
      : `FirestoreJobStatus${goName(name)}`;
    return optional ? `*${typ}` : typ;
  }
  const typ = prop.type === 'integer' || prop.type === 'number' ? 'int' : 'string';
  return optional ? `*${typ}` : typ;
}

const goLines = [
  '// Code generated by scripts/generate-firestore-types.mjs; DO NOT EDIT.',
  '// Source: contracts/firestore/job-status.schema.json',
  '',
  'package jobstatus',
  '',
  'const FirestoreJobStatusJSONSchema = `' + JSON.stringify(schema, null, 2).replaceAll('`', '` + "`" + `') + '`',
  '',
  'type FirestoreJobStatusState string',
  '',
  'const (',
];

for (const value of schema.properties.status.enum) {
  const suffix = value[0].toUpperCase() + value.slice(1);
  goLines.push(`\tFirestoreJobStatusState${suffix} FirestoreJobStatusState = ${JSON.stringify(value)}`);
}

goLines.push(')', '');

for (const [name, prop] of Object.entries(schema.properties ?? {})) {
  if (!Array.isArray(prop.enum) || name === 'status') continue;
  const typ = `FirestoreJobStatus${goName(name)}`;
  goLines.push(`type ${typ} string`, '', 'const (');
  for (const value of prop.enum) {
    const suffix = value.split(/[._-]/).map((part) => part[0].toUpperCase() + part.slice(1)).join('');
    goLines.push(`\t${typ}${suffix} ${typ} = ${JSON.stringify(value)}`);
  }
  goLines.push(')', '');
}

goLines.push('const (');
for (const name of Object.keys(schema.properties ?? {})) {
  goLines.push(`\tFirestoreJobStatusField${goName(name)} = ${JSON.stringify(name)}`);
}
goLines.push(')', '');

goLines.push('type FirestoreJobStatus struct {');
for (const [name, prop] of Object.entries(schema.properties ?? {})) {
  const optional = !required.has(name);
  const omitempty = optional ? ',omitempty' : '';
  goLines.push(`\t${goName(name)} ${goType(name, prop, optional)} \`firestore:"${name}${omitempty}" json:"${name}${omitempty}"\``);
}
goLines.push('}', '');

writeFileSync(goOutPath, goLines.join('\n'));

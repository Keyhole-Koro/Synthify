// target here; everything below is driven by this list.
//
// typeName prefixes every generated Go identifier and names the TS type.
// goNameOverrides fixes initialisms that the default capitalisation gets wrong
// (id -> ID, url -> URL); anything absent just gets its first letter upcased.
